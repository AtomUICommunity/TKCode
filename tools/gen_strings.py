#!/usr/bin/env python3
"""从 Localization/strings.tsv 生成 Arc 语言目录：TKCodeLangResourceKind.g.cs、en-US.xlf、zh-CN.xlf。

Arc 要求枚举成员与 XLIFF unit 一一对应、zh-CN 的 source 与 en-US 完全一致，
所以三者只从这一份表生成。用法：python3 -I tools/gen_strings.py
"""
import pathlib
from xml.sax.saxutils import escape

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIR = ROOT / "src/TKCode.Desktop/Localization"
NAMESPACE = "TKCode.Desktop.Localization"
ENUM = "TKCodeLangResourceKind"


def load():
    rows = []
    for line in (DIR / "strings.tsv").read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        key, en, zh = line.split("\t")
        rows.append((key, en, zh))
    keys = [k for k, _, _ in rows]
    dupes = {k for k in keys if keys.count(k) > 1}
    if dupes:
        raise SystemExit(f"duplicate keys: {sorted(dupes)}")
    return rows


def xliff(rows, lang):
    trg = '' if lang is None else f' trgLang="{lang}"'
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- 由 tools/gen_strings.py 从 strings.tsv 生成，请勿手改。 -->',
           f'<xliff version="2.1" srcLang="en-US"{trg} xmlns="urn:oasis:names:tc:xliff:document:2.0">',
           f'  <file id="{NAMESPACE}.{ENUM}">']
    for key, en, zh in rows:
        target = '' if lang is None else f'<target state="translated">{escape(zh)}</target>'
        out.append(f'    <unit id="{key}"><segment><source>{escape(en)}</source>{target}</segment></unit>')
    out += ['  </file>', '</xliff>', '']
    return "\n".join(out)


def main():
    rows = load()
    enum = ["// <auto-generated>由 tools/gen_strings.py 从 strings.tsv 生成，请勿手改。</auto-generated>",
            "using TKCode.Arc.Localization;", "", f"namespace {NAMESPACE};", "",
            "/// <summary>TKCode 界面文案。AXAML 中使用 {loc:TKCodeLangResource Key}，C# 中使用 Strings.Get / Format。</summary>",
            "[LanguageCatalog]", f"public enum {ENUM}", "{"]
    enum += [f"    {k}," for k, _, _ in rows]
    enum += ["}", ""]
    (DIR / f"{ENUM}.g.cs").write_text("\n".join(enum), encoding="utf-8")
    (DIR / "en-US.xlf").write_text(xliff(rows, None), encoding="utf-8")
    (DIR / "zh-CN.xlf").write_text(xliff(rows, "zh-CN"), encoding="utf-8")
    print(f"{len(rows)} strings")


if __name__ == "__main__":
    main()
